import assert from 'node:assert/strict';
import {Keypair}from'@solana/web3.js';
import nacl from'tweetnacl';
import{readFileSync}from'node:fs';
const base=process.env.DEMO_API_URL||'http://localhost:8090';
assert.ok(['localhost','127.0.0.1'].includes(new URL(base).hostname));
async function call(path,body,headers={}){const r=await fetch(`${base}/v1${path}`,{method:body?'POST':'GET',headers:{'content-type':'application/json',...headers},...(body?{body:JSON.stringify(body)}:{})});return{status:r.status,body:await r.json()};}
const signup=await call('/auth/signup',{email:`diamond-check-${Date.now()}@example.invalid`,password:'isolated-devnet-check-2026',displayName:'Wallet verification TEST'});
assert.equal(signup.status,200);
const auth={authorization:`Bearer ${signup.body.sessionToken}`};
assert.equal((await call('/collectibles/handoff',{})).status,401);
const handoff=await call('/collectibles/handoff',{},auth);assert.equal(handoff.status,200);
const ticket=new URL(handoff.body.url).hash.slice(1);
const session=await call('/collectibles/session',{ticket});assert.equal(session.status,200);
assert.equal((await call('/collectibles/session',{ticket})).status,401);
const headers={'x-collectible-session':session.body.token};
const pair=Keypair.generate();const address=pair.publicKey.toBase58();
const challenge=await call('/collectibles/wallet/challenge',{address},headers);assert.equal(challenge.status,200);
assert.equal((await call('/collectibles/wallet/verify',{signature:Buffer.alloc(64).toString('base64')},headers)).status,400);
const signature=nacl.sign.detached(Buffer.from(challenge.body.message),pair.secretKey);
assert.equal((await call('/collectibles/wallet/verify',{signature:Buffer.from(signature).toString('base64')},headers)).body.address,address);
assert.equal((await call('/collectibles/wallet/verify',{signature:Buffer.from(signature).toString('base64')},headers)).status,400);
assert.equal((await call('/collectibles/wallet/challenge',{address:Keypair.generate().publicKey.toBase58()},headers)).status,400);
const fixture=JSON.parse(readFileSync(process.env.DIAMOND_FIXTURE_FILE,'utf8').split('\nSeeded')[0]);
const rejected=await call('/collectibles/claim',{playerId:fixture.playerId},headers);assert.equal(rejected.status,400);assert.match(rejected.body.message,/400/);
const login=await call('/auth/login',{email:fixture.earnerEmail,password:fixture.password});
const progress=await call('/collectibles/dashboard',null,{authorization:`Bearer ${login.body.sessionToken}`});
assert.equal(progress.status,200);assert.equal(progress.body.cards[0].qualifying_calls,400);assert.equal(progress.body.cards[0].mastery_calls,'400');
console.log('PASS authenticated handoff, one-use tickets, wallet proof, replay rejection, wallet mismatch rejection, unearned claim rejection, settled 400-call entitlement.');
